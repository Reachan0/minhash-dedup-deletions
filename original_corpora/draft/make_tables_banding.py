#!/usr/bin/env python3
"""Emit the banding-sweep table from results/banding_sweep.json.

Output: paper/tables/tab2_banding.tex. Every cell is a five-seed mean from the JSON.
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
SRC = os.path.join(ROOT, "output/dedupjoin-pvldb/results/banding_sweep.json")
OUT = os.path.join(ROOT, "output/dedupjoin-pvldb/paper/tables/tab2_banding.tex")
CORP = [("c4", "C4"), ("fw", "FineWeb"), ("mix", "Mix"), ("wet", "WET snap.")]
CFG = [("14x8", "14$\\times$8"), ("20x5", "20$\\times$5"),
       ("26x11", "26$\\times$11"), ("10x10", "10$\\times$10")]


def f0(x):
    return f"{int(round(x)):,}".replace(",", "{,}")


def main():
    d = json.load(open(SRC))
    lines = [
        "% generated by code/make_tables_banding.py from results/banding_sweep.json",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Banding sweep at $\\tau=0.8$, mean over five hash seeds, every deletion",
        "classified against the same exact truth. \\emph{design}: similarity at which the",
        "configuration's S-curve reaches 0.5; \\emph{del.}: raw LSH deletions; \\emph{unsup.}:",
        "deletions with no neighbour at exact $J\\geq\\tau$, with its share of deletions;",
        "\\emph{missed}: exact deletions the configuration's verified edges never reach;",
        "\\emph{recall}: pair recall of the candidate edges.}",
        "\\label{tab:banding}",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}llrrrrrr@{}}",
        "\\toprule",
        "Corpus & Config. & design & del. & unsup. & unsup.\\,\\% & missed & recall \\\\",
        "\\midrule",
    ]
    for key, name in CORP:
        if key not in d:
            continue
        for cfg, cname in CFG:
            v = d[key].get(cfg, {}).get("0.8")
            if not v:
                continue
            lines.append(
                f"{name} & {cname} & {v['design_threshold']:.2f} & {f0(v['deleted_mean'])} & "
                f"{f0(v['unsupported_mean'])} & {100*v['unsupported_frac_mean']:.1f} & "
                f"{f0(v['missed_mean'])} & {v['pair_recall_mean']:.3f} \\\\"
            )
        lines.append("\\addlinespace")
    if lines[-1] == "\\addlinespace":
        lines.pop()
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
