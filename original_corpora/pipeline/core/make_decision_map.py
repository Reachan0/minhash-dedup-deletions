#!/usr/bin/env python3
"""Emit core/decision_map.md from the decision table (all numbers read from disk).

Policies
  cheapest          minimum incremental wall time among all paths
  justified         minimum incremental wall time among paths whose deletions carry no
                    unsupported share (deletion set closed under the exact relation)
  witnessed         path W, i.e. every deletion has a retained direct exact neighbour
  exact             path C, the closed exact answer used as reference
"""
import csv
import json
import os

CORE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.abspath(os.path.join(CORE, "..", "..", "core"))


def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def main():
    rows = list(csv.DictReader(open(os.path.join(OUT, "main_decision_table.csv"))))
    lines = ["# Decision map — which deduplication path to run",
             "",
             "Generated by `make_decision_map.py` from `main_decision_table.csv`; every number",
             "below is read from that file (evidence tier: rerun, medians over fresh OS",
             "processes, 12 threads, min-id representative). Paths:",
             "",
             "- **A** — production raw MinHash-LSH chain (datatrove 0.6.0 equivalent): band",
             "  collisions, consecutive-signature pairs only, union-find. No all-pairs, no",
             "  verification.",
             "- **B** — LSH candidates plus exact Jaccard verification of every candidate pair;",
             "  every deletion rests on a verified edge.",
             "- **W** — B's verified graph, but deletions are a greedy independent set: a",
             "  document is deleted only if a retained direct exact neighbour survives.",
             "- **C** — full exact Jaccard self-join: the closed reference set.",
             ""]
    by = {}
    for r in rows:
        if r["representative"] != "minid":
            continue
        by.setdefault((r["workload"], float(r["tau"])), {})[r["method"]] = r
    for (w, tau) in sorted(by):
        cell = by[(w, tau)]
        n = cell["A"]["n"]

        def t(m):
            v = num(cell[m].get("incremental_median_s"))
            return v if v is not None else float("inf")

        def unsup(m):
            v = num(cell[m].get("unsupported_share_del_mean"))
            return v if v is not None else float("nan")

        cheapest = min(cell, key=t)
        closed = [m for m in cell if not (unsup(m) > 0)]
        justified = min(closed, key=t) if closed else None
        lines.append(f"## {w}, τ = {tau} (n = {int(float(n)):,})")
        lines.append("")
        lines.append("| Path | Deleted | Unsupported share | Residual pairs | Witness coverage "
                     "| Incremental (s) | Cold (s) | Peak RSS (MB) |")
        lines.append("|---|---|---|---|---|---|---|---|")
        for m in ("A", "B", "W", "C"):
            r = cell[m]
            cold = num(r.get("cold_median_s"))
            cold_s = f"{cold:.1f}" if cold is not None else (
                f"{num(r.get('cold_composed_median_s')):.1f} (composed)"
                if num(r.get("cold_composed_median_s")) is not None else "--")
            lines.append(
                f"| {m} | {num(r['deleted_mean']):.0f} | "
                f"{100 * unsup(m):.2f}% | "
                f"{num(r['residual_duplicate_pairs_mean']):.0f} | "
                f"{num(r['witness_coverage_mean']):.3f} | {t(m):.2f} | {cold_s} | "
                f"{num(r.get('incremental_peak_rss_mb')):.0f} |")
        lines.append("")
        lines.append(f"- Cheapest path: **{cheapest}** ({t(cheapest):.2f} s incremental), "
                     f"{100 * unsup(cheapest):.2f}% of its deletions unsupported."
                     + (" Its incremental figure assumes the exact-join rank cache exists; "
                        "the rank build is charged to its cold row." if cheapest == "C" else ""))
        if justified == "C":
            lines.append(f"- Closed exact answer: **C** ({t('C'):.2f} s incremental with the "
                         "rank cache present; cold includes the rank build). It has no "
                         "LSH-missed edges by construction and is the reference set.")
        elif justified:
            lines.append(f"- Cheapest closed-deletion path: **{justified}** "
                         f"({t(justified):.2f} s); every deletion it makes is backed by a "
                         "verified exact edge, at the price of LSH-missed edges.")
        else:
            lines.append("- No path has a zero unsupported share in this cell.")
        lines.append(f"- Witness guarantee: **W** at {t('W'):.2f} s, witness coverage "
                     f"{num(cell['W']['witness_coverage_mean']):.3f}, "
                     f"{num(cell['W']['residual_duplicate_pairs_mean']):.0f} residual "
                     "duplicate pairs left in the retained set.")
        lines.append("")
    lines += [
        "## Rules of thumb",
        "",
        "1. Use **A** only when the deletion policy accepts collapsing a near-duplicate "
        "cluster without keeping a direct neighbour of every removed document — it is the "
        "fastest path and the only one that preserves the production datatrove behaviour, "
        "but its unsupported share is large.",
        "2. Use **B** when every deletion must be justified by an exact Jaccard comparison "
        "and a small residual of LSH-missed pairs is tolerable.",
        "3. Use **W** when the policy additionally requires that every deleted document has "
        "a retained direct exact neighbour (auditable deletion).",
        "4. Use **C** as the reference and for any corpus small enough that its memory and "
        "join cost are affordable; it is the only closed answer.",
        "5. τ = 0.75 buys additional deletions at higher candidate and verification cost; "
        "the ranking of paths does not change with τ.",
        "",
    ]
    p = os.path.join(OUT, "decision_map.md")
    open(p, "w").write("\n".join(lines))
    print("wrote", p)


if __name__ == "__main__":
    main()
