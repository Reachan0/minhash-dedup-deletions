#!/usr/bin/env python3
"""tables/tab_ladder.tex: operator cost on the nested corpora, seed 1, tau 0.8, Gold 6430.

Signatures, A, streaming B and exact W: data/ladder_ops.jsonl (ladder_ops.py, document level, each
operator in its own process). C: data/rung_<N>.jsonl corpus rows (b1_rung.py), which build the rank
index once and run the exact join on collapsed shingle sets; peak memory there is the whole harness.
Usage: python3 make_tab_ladder.py [paper dir]
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
P = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out")
for _d in ("tables", "figures"):
    os.makedirs(os.path.join(P, _d), exist_ok=True)
D = os.path.join(HERE, "..", "results", "paper")
RUNGS = ((531597, "0.53M"), (1000000, "1.0M"), (2000000, "2.0M"), (3000000, "3.0M"))
ops = [json.loads(l) for l in open(os.path.join(D, "ladder_ops.jsonl"))]


def op(n, kind):
    hit = [r for r in ops if r["corpus"] == f"rung_{n}" and r["kind"] == kind and r.get("status") == "ok"]
    return hit[-1]


def mill(x):
    return f"{x / 1e6:.1f}M"


body, summary = [], {}
for n, lab in RUNGS:
    k, s, w = op(n, "keys"), op(n, "stream"), op(n, "W")
    assert s.get("equals_B"), (n, "streaming B differs from B")
    c = [json.loads(l) for l in open(os.path.join(D, f"rung_{n}.jsonl"))]
    c = [r for r in c if r.get("kind") == "corpus"][0]
    sig, ta, tb, tw = k["t_signature_s"], k["t_after_signature_s"], s["t_after_signature_s"], w["t_after_signature_s"]
    summary[lab] = dict(sig=sig, A=ta, B=tb, W=tw, verified=s["verified_pairs"], verified_per_doc=s["verified_pairs"] / s["n"],
                        gib=max(k["peak_rss_gib"], s["peak_rss_gib"]), slower=(sig + tb) / (sig + ta) - 1,
                        c_index=c["t_ranks_s"], c_join=c["t_truth_s"]["0.8"])
    body.append(f"{lab} & {sig:.1f} & {ta:.1f} & {tb:.1f} & {mill(s['verified_pairs'])} & {s['peak_rss_gib']:.1f} & "
                f"{tw:.1f} & {c['t_ranks_s']:,.0f} + {c['t_truth_s']['0.8']:.1f} \\\\")
print(json.dumps(summary, indent=1))
tex = r"""% generated by scripts/make_tab_ladder.py from data/ladder_ops.jsonl and data/rung_*.jsonl
\begin{table}[t]
\centering
\caption{Cost on the nested corpora, seed 1, $\tau=0.8$, seconds on the Gold 6430. A, B and W start from signatures; C builds a rank index once on collapsed shingle sets, then joins.}
\label{tab:ladder}
\small
\setlength{\tabcolsep}{3pt}
\begin{tabular}{@{}lrrrrrrr@{}}
\toprule
 & & & \multicolumn{3}{c}{Streaming B} & & \\
\cmidrule(lr){4-6}
Docs & Sig. & A & Time & Verified & GiB & W & C \\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
open(os.path.join(P, "tables", "tab_ladder.tex"), "w").write(tex)
print(tex)
