#!/usr/bin/env python3
"""tables/tab_adv.tex from data/adv_bucket.jsonl (adv_bucket.py on AutoDL, one core per run).
Usage: python3 make_tab_adv.py [paper dir]
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
P = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out")
for _d in ("tables", "figures"):
    os.makedirs(os.path.join(P, _d), exist_ok=True)
rows = [json.loads(l) for l in open(os.path.join(HERE, "..", "results", "paper", "adv_bucket.jsonl"))]
# the rerun that records the component bound; its counters must equal the rows above
cap4 = [json.loads(l) for l in open(os.path.join(HERE, "..", "results", "paper", "adv_bucket_cap4.jsonl"))]


def sci(x):
    e = int(math.floor(math.log10(x)))
    m = x / 10 ** e
    return f"${m:.1f}\\cdot10^{{{e}}}$"


def cell(r):
    if r is None:
        return "--"
    if r["status"] != "ok":
        return r["status"]
    return f"{sci(r['verified_pairs'])} / {r['t_s']:.1f}\\,s"


def cap_extra(r):
    if r is None or r["status"] != "ok":
        return "--"
    b = [x for x in cap4 if x["groups"] == r["groups"] and x["m"] == r["m"] and x["kind"] == "cap"][-1]
    for k in ("verified_pairs", "unchecked_U", "extra_retained", "deleted"):
        assert b[k] == r[k], (r["groups"], r["m"], k, b[k], r[k])
    u = sci(r["unchecked_U"]) if r["unchecked_U"] else "0"
    return f"{r['extra_retained']:,} / {b['extra_bound']:,} / {u}"


def get(g, m, k):
    hit = [r for r in rows if r["groups"] == g and r["m"] == m and r["kind"] == k]
    return hit[-1] if hit else None


body = []
GROUPS = (("two", "Two groups"), ("distinct", "No duplicates"), ("noisy", "Unrelated first"))
for g, lab in GROUPS:
    for m in (10000, 30000, 100000):
        body.append(" & ".join([lab if m == 10000 else "", f"{m:,}", cell(get(g, m, "stream")), cell(get(g, m, "W")),
                                cell(get(g, m, "cap")), cap_extra(get(g, m, "cap"))]) + " \\\\")
    if g != GROUPS[-1][0]:
        body.append("\\addlinespace")
tex = r"""% generated by scripts/make_tab_adv.py from data/adv_bucket.jsonl and data/adv_bucket_cap4.jsonl
\begin{table*}[t]
\centering
\caption{One synthetic bucket of $m$ documents: two groups of near-duplicates, no duplicates, or one group whose bucket's first member is unrelated to it. Similarity tests and time on one core of the Gold 6430; capped B with $q=1{,}000$.}
\label{tab:adv}
\small
\setlength{\tabcolsep}{6pt}
\begin{tabular}{@{}lrllll@{}}
\toprule
Bucket & $m$ & Streaming B & Exact W & Capped B & Capped B: extra / bound / $U$ \\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}
\end{table*}
"""
open(os.path.join(P, "tables", "tab_adv.tex"), "w").write(tex)
print(tex)
