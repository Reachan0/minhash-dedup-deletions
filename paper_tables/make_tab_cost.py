#!/usr/bin/env python3
"""tables/tab_cost.tex from data/b2_runs.jsonl (literal, streaming, exact W; server) and
data/b2_cap2.jsonl (capped B with two star passes exempt from the cap; AutoDL, same variants rebuilt
with the same seeds). Pairs per document = within-bucket pairs enumerated by
streaming B over all 14 bands, divided by the corpus size.
Usage: python3 make_tab_cost.py [paper dir]
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
P = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out")
for _d in ("tables", "figures"):
    os.makedirs(os.path.join(P, _d), exist_ok=True)
D = os.path.join(HERE, "..", "results", "paper")
N = 429221
VARIANTS = (("base", "None"), ("exact_1000", "$10^3$ copies"), ("exact_10000", "$10^4$ copies"),
            ("exact_100000", "$10^5$ copies"), ("near_1000", "$10^3$ near-copies"),
            ("near_10000", "$10^4$ near-copies"), ("near_100000", "$10^5$ near-copies"))


def rows(name):
    p = os.path.join(D, name)
    return [json.loads(l) for l in open(p)] if os.path.exists(p) else []


def pick(rs, v, kind, q=None):
    hit = [r for r in rs if r["variant"] == v and r["kind"] == kind and (q is None or r.get("q") == q)]
    return hit[-1] if hit else None


def t(r, mem=True):
    if r is None:
        return "--"
    if r.get("status") != "ok":
        return "fails"
    return f"{r['t_method_s']:.1f}\\,s" + (f" / {r['peak_rss_gib']:.1f}\\,GiB" if mem else "")


def k(x):
    return f"{x / 1e3:,.0f}k" if x < 1e6 else (f"{x / 1e6:,.1f}M" if x < 1e9 else f"{x / 1e9:,.1f}G")


def main():
    runs = rows("b2_runs.jsonl")
    cap = [r for r in rows("b2_cap2.jsonl") if not r.get("cap_prefix")]
    cap4 = [r for r in rows("b2_cap4.jsonl") if not r.get("cap_prefix")]
    body = []
    for v, lab in VARIANTS:
        s, lit, w, c = pick(runs, v, "stream"), pick(runs, v, "literal"), pick(runs, v, "W"), pick(cap, v, "cap", 1000)
        ppd = f"{s['enumerated_pairs'] / N:,.1f}" if s and s["enumerated_pairs"] / N < 100 else (f"{s['enumerated_pairs'] / N:,.0f}" if s else "--")
        c4 = pick(cap4, v, "cap", 1000)
        for f in ("verified_pairs", "unchecked_U", "extra_retained", "deleted"):
            assert c4[f] == c[f], (v, f, c4[f], c[f])
        capcell = f"{c['extra_retained']:,} / {c4['extra_bound']:,} / {k(c['unchecked_U'])}" if c and c.get("status") == "ok" else "--"
        body.append(" & ".join([lab, ppd, t(lit), t(s), k(s["verified_pairs"]) if s else "--", t(w, mem=False), capcell]) + " \\\\")
        if v == "exact_100000":
            body.append("\\addlinespace")
    tex = r"""% generated by scripts/make_tab_cost.py from data/b2_runs.jsonl, data/b2_cap2.jsonl and data/b2_cap4.jsonl
\begin{table*}[t]
\centering
\caption{Verification cost after injecting $m$ copies or near-copies of one page into Snapshot-2025 ($\geq$50 words), one seed, time after signatures on the Silver 4110; materialised B is limited to 24\,GiB. Capped B ($q=1{,}000$, Algorithm~\ref{alg:stream}) keeps \emph{extra} documents beyond B, at most the \emph{bound}, and leaves $U$ pairs untested.}
\label{tab:cost}
\small
\setlength{\tabcolsep}{4pt}
\begin{tabular}{@{}lrrrrrr@{}}
\toprule
Injected & Pairs/doc & Materialised B & Streaming B & Verified pairs & Exact W & Capped B: extra / bound / $U$ \\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}
\end{table*}
"""
    open(os.path.join(P, "tables", "tab_cost.tex"), "w").write(tex)
    print(tex)


if __name__ == "__main__":
    main()
